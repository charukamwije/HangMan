"""
Builds src/data/library.ts from puzzles/dark-board-100.csv (the video library in the studio).
Checks every row (prefill letter, yes/miss against the answer, end board) and stops on a mismatch.

    python scripts/build-library.py
"""
import csv
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "puzzles" / "dark-board-100.csv"
OUT = ROOT / "src" / "data" / "library.ts"

rows = []
errors = []
with SRC.open(encoding="utf-8", newline="") as f:
    for r in csv.DictReader(f):
        n = int(r["#"])
        word = r["Answer"].strip().upper()
        board0 = r["Board at 0 s"].split()
        prefill = sorted({c for c in board0 if c != "_"})
        guesses = [(m[0], m[1] == "yes") for m in re.findall(r"\d+\.\s*([A-Z])\((yes|miss)\)", r["Reveal order (one guess about every 3 s)"])]
        if len(board0) != len(word):
            errors.append(f"#{n}: board at 0 s has {len(board0)} slots, answer has {len(word)}")
        if len(prefill) != 1:
            errors.append(f"#{n}: expected one pre-filled letter, got {prefill}")
        for i, c in enumerate(board0):
            if c != "_" and (i >= len(word) or word[i] != c):
                errors.append(f"#{n}: board at 0 s letter {c} is not at slot {i + 1} of {word}")
        for letter, yes in guesses:
            if (letter in word) != yes:
                errors.append(f"#{n}: {letter} marked {'yes' if yes else 'miss'} but {'is not' if yes else 'is'} in {word}")
        shown = set(prefill) | {l for l, yes in guesses if yes}
        end = " ".join(c if c in shown else "_" for c in word)
        if end != r["Board at the end (comment bait)"].strip():
            errors.append(f"#{n}: end board {end} does not match {r['Board at the end (comment bait)']}")
        rows.append(
            {
                "n": n,
                "word": word,
                "category": r["Category tag"].strip(),
                "hookText": r["Hook banner (on screen at 0 s)"].strip().upper(),
                "hint1": r["Hint 1 (0 s)"].strip(),
                "hint2": r["Hint 2 (at 15 s)"].strip(),
                "prefill": prefill[0] if prefill else "",
                "guesses": [{"letter": l, "correct": yes} for l, yes in guesses],
                # "Show" (current CSV) or "Source" (older CSV): the series the word comes from.
                "source": (r.get("Show") or r.get("Source") or "").strip(),
            }
        )

if errors:
    print("\n".join(errors))
    sys.exit(1)

OUT.parent.mkdir(parents=True, exist_ok=True)
body = ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in rows)
OUT.write_text(
    f"""// GENERATED by scripts/build-library.py from puzzles/dark-board-100.csv. Edit the CSV, then re-run the script.

export type LibraryGuess = {{ letter: string; correct: boolean }};

export type LibraryEntry = {{
  /** Video number (1-based, as in the CSV). */
  n: number;
  word: string;
  category: string;
  /** Banner text on screen from 0 s (uppercased). */
  hookText: string;
  /** Hint 1 (0 s). */
  hint1: string;
  /** Hint 2 (15 s). */
  hint2: string;
  /** The letter already on the board at 0 s. */
  prefill: string;
  /** Reveal order: one guess about every 3 s. */
  guesses: LibraryGuess[];
  source: string;
}};

export const LIBRARY: LibraryEntry[] = [
{body},
];
""",
    encoding="utf-8",
    newline="\n",
)
print(f"Wrote {len(rows)} videos to {OUT.relative_to(ROOT)}")
