"""
Builds the studio's video libraries from the CSVs in puzzles/:

    K-Drama  puzzles/kdrama-1000.csv     -> src/data/library-kdrama.ts  (theme: Seoul Cherry Blossom Night)
    Other    puzzles/dark-board-100.csv  -> src/data/library-other.ts   (theme: Midnight Noir)

and src/data/library.ts (types + the LIBRARIES list the studio's dropdown uses).
Checks every row (prefill letter, yes/miss against the answer, end board). Rows that fail are
skipped and listed (e.g. three letters pre-filled; the reel seats two); the video keeps its CSV number so numbering never shifts.

    python scripts/build-library.py
"""
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "src" / "data"

# id, label, CSV, default theme, file-name prefix for renders / screenshots / thumbnails
LIBRARIES = [
    ("kdrama", "K-Drama", "kdrama-1000.csv", "seoul-blossom", "kdrama"),
    ("other", "Other", "dark-board-100.csv", "midnight-noir", "video"),
]


def build(csv_name):
    rows, errors = [], []
    with (ROOT / "puzzles" / csv_name).open(encoding="utf-8-sig", newline="") as f:
        for r in csv.DictReader(f):
            n = int(r["#"])
            word = r["Answer"].strip().upper()
            board0 = r["Board at 0 s"].split()
            prefill = sorted({c for c in board0 if c != "_"})
            guesses = [(m[0], m[1] == "yes") for m in re.findall(r"\d+\.\s*([A-Z])\((yes|miss)\)", r["Reveal order (one guess about every 3 s)"])]
            bad = []
            if len(board0) != len(word):
                bad.append(f"board at 0 s has {len(board0)} slots, answer has {len(word)}")
            # One letter on the board at 0 s, or two (hint + 2nd letter): the reel seats at most two.
            if len(prefill) not in (1, 2):
                bad.append(f"expected one or two pre-filled letters, got {prefill}")
            for i, c in enumerate(board0):
                if c != "_" and (i >= len(word) or word[i] != c):
                    bad.append(f"board at 0 s letter {c} is not at slot {i + 1}")
            for letter, yes in guesses:
                if (letter in word) != yes:
                    bad.append(f"{letter} marked {'yes' if yes else 'miss'} but {'is not' if yes else 'is'} in the word")
            shown = set(prefill) | {l for l, yes in guesses if yes}
            end = " ".join(c if c in shown else "_" for c in word)
            if end != r["Board at the end (comment bait)"].strip():
                bad.append(f"end board should be {end}, CSV has {r['Board at the end (comment bait)'].strip()}")
            if bad:
                errors.append(f"  #{n} {word}: " + "; ".join(bad))
                continue
            rows.append(
                {
                    "n": n,
                    "word": word,
                    "category": r["Category tag"].strip(),
                    "hookText": r["Hook banner (on screen at 0 s)"].strip().upper(),
                    "hint1": r["Hint 1 (0 s)"].strip(),
                    "hint2": r["Hint 2 (at 15 s)"].strip(),
                    "prefill": prefill[0],
                    # Second letter already on the board at 0 s ("" = none: the first correct guess is used).
                    "prefill2": prefill[1] if len(prefill) > 1 else "",
                    "guesses": [{"letter": l, "correct": yes} for l, yes in guesses],
                    # "Show" (current CSVs) or "Source" (older CSV): the series the word comes from.
                    "source": (r.get("Show") or r.get("Source") or "").strip(),
                }
            )
    return rows, errors


def const_name(lib_id):
    return f"{lib_id.upper()}_ENTRIES"


for lib_id, label, csv_name, theme, prefix in LIBRARIES:
    rows, errors = build(csv_name)
    body = ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in rows)
    (DATA / f"library-{lib_id}.ts").write_text(
        f"// GENERATED by scripts/build-library.py from puzzles/{csv_name}. Edit the CSV, then re-run the script.\n\n"
        f'import type {{ LibraryEntry }} from "./library";\n\n'
        f"export const {const_name(lib_id)}: LibraryEntry[] = [\n{body},\n];\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{label}: {len(rows)} videos from puzzles/{csv_name}" + (f", {len(errors)} skipped:" if errors else ""))
    for e in errors:
        print(e)

imports = "\n".join(f'import {{ {const_name(i)} }} from "./library-{i}";' for i, *_ in LIBRARIES)
ids = " | ".join(f'"{i}"' for i, *_ in LIBRARIES)
entries = "\n".join(
    f'  {{ id: "{i}", label: "{label}", themeId: "{theme}", filePrefix: "{prefix}", entries: {const_name(i)} }},'
    for i, label, _csv, theme, prefix in LIBRARIES
)
(DATA / "library.ts").write_text(
    f"""// GENERATED by scripts/build-library.py. Edit the CSVs in puzzles/, then re-run the script.

import type {{ ThemeId }} from "@/remotion/themes";
{imports}

export type LibraryGuess = {{ letter: string; correct: boolean }};

export type LibraryEntry = {{
  /** Video number (1-based, as in the CSV). */
  n: number;
  word: string;
  category: string;
  /** Banner text on screen from 0 s (uppercased). */
  hookText: string;
  /** Hint 1 (0 s). */
  hint1: string;
  /** Hint 2 (15 s). */
  hint2: string;
  /** The letter already on the board at 0 s. */
  prefill: string;
  /** A second letter already on the board at 0 s ("" = none; the first correct guess is pre-filled instead). */
  prefill2: string;
  /** Reveal order: one guess about every 3 s. */
  guesses: LibraryGuess[];
  source: string;
}};

export type LibraryId = {ids};

export type Library = {{
  id: LibraryId;
  label: string;
  /** Theme selected automatically when this library is picked. */
  themeId: ThemeId;
  /** Start of render / screenshot / thumbnail file names, e.g. kdrama-007-WORD. */
  filePrefix: string;
  entries: LibraryEntry[];
}};

export const LIBRARIES: Library[] = [
{entries}
];

export const DEFAULT_LIBRARY_ID: LibraryId = "other";

export const getLibrary = (id: LibraryId | undefined): Library => LIBRARIES.find((l) => l.id === id) ?? LIBRARIES.find((l) => l.id === DEFAULT_LIBRARY_ID)!;

/** File-name base for a library video, e.g. kdrama-007-HONEYCOMB / video-012-DEMOGORGON. */
export const libraryFileBase = (id: LibraryId | undefined, n: number, word: string) =>
  `${{getLibrary(id).filePrefix}}-${{String(n).padStart(3, "0")}}-${{word}}`;
""",
    encoding="utf-8",
    newline="\n",
)
